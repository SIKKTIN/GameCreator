import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {rolldown} from 'rolldown';
const bundle=await rolldown({input:fileURLToPath(new URL('../src/project-content-model.ts',import.meta.url)),platform:'node',treeshake:true});
const result=await bundle.generate({format:'cjs',minify:false});await bundle.close();
const code='// Generated by scripts/build-project-content-model.mjs.\n'+result.output[0].code;
const file=new URL('../desktop/project-content-model.cjs',import.meta.url);
if(process.argv.includes('--check')){if((await fs.readFile(file,'utf8').catch(()=>'')).replace(/\r\n/g,'\n')!==code.replace(/\r\n/g,'\n'))throw new Error('Run node scripts/build-project-content-model.mjs to update project content validators');}
else await fs.writeFile(file,code);
