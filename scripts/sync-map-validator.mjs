import fs from 'node:fs';
import ts from 'typescript';
const source=fs.readFileSync(new URL('../src/map-design.ts',import.meta.url),'utf8');
const file=ts.createSourceFile('map-design.ts',source,ts.ScriptTarget.Latest,true);
const fn=file.statements.find(n=>ts.isFunctionDeclaration(n)&&n.name?.text==='validateMapDesign');
if(!fn)throw new Error('Map validator not found');
const code=ts.transpileModule(fn.getText(file).replace('export function validateMapDesign','function validateMapArchive'),{compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText.trim();
const target=new URL('../desktop/project-package.cjs',import.meta.url),desktop=fs.readFileSync(target,'utf8');
const start=desktop.indexOf('function validateMapArchive('),end=desktop.indexOf('function validateStoryArchive(');
if(end<0)throw new Error('Desktop validator boundary not found');
fs.writeFileSync(target,desktop.slice(0,start<0?end:start)+code+'\n'+desktop.slice(end));
