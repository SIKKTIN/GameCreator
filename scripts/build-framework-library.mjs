import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=fileURLToPath(new URL('../',import.meta.url));
const entries=[
  ['intro','README.md','开始阅读','reference'],
  ['architecture','基础规范/01_架构总纲.md','基础规范','base'],
  ['package','基础规范/02_Package组织与公共接口.md','基础规范','base'],
  ['core','基础规范/03_Core边界与公共机制.md','基础规范','base'],
  ['data','基础规范/04_数据与配置.md','基础规范','base'],
  ['events','基础规范/05_调用与事件.md','基础规范','base'],
  ['lifecycle','基础规范/06_依赖与生命周期.md','基础规范','base'],
  ['testing','开发规范/01_开发测试与调试.md','开发规范','base'],
  ['review','开发规范/02_评审与交付检查.md','开发规范','base'],
  ['save','可选扩展/01_存档与数据迁移.md','可选扩展','extension'],
  ['state','可选扩展/02_数据注册与集中管理.md','可选扩展','extension'],
  ['assembly','可选扩展/03_模块声明与自动装配.md','可选扩展','extension'],
  ['network','可选扩展/04_联机与状态同步.md','可选扩展','extension'],
  ['engine','引擎接入/01_接入原则.md','引擎接入','base'],
  ['oasis','引擎接入/02_绿洲启元补充.md','引擎接入','engine'],
  ['planting','示例/01_单机种植与背包.md','示例','reference'],
  ['structure','示例/02_最小项目结构.md','示例','reference'],
  ['migration','迁移指南.md','迁移指南','reference'],
];
const documents=[];
for(const [id,filename,group,kind] of entries) {
  const content=(await fs.readFile(path.join(root,'frameworks/package-core-v1',filename),'utf8')).replaceAll('\r\n','\n').trim()+'\n';
  documents.push({id,path:filename,title:content.split('\n')[0].replace(/^# /,''),group,kind,content});
}
const output='// Generated by scripts/build-framework-library.mjs. Edit frameworks/package-core-v1 instead.\nexport const frameworkLibrary = '+JSON.stringify({id:'package-core',version:'1.0',title:'通用游戏项目框架',documents},null,2)+';\n';
const target=path.join(root,'shared/program-framework-library.mjs');
if(process.argv.includes('--check')) {
  if((await fs.readFile(target,'utf8')).replaceAll('\r\n','\n')!==output)throw new Error('内置程序框架文档已变化，请运行 node scripts/build-framework-library.mjs');
  console.log('Framework library is current: '+documents.length+' documents.');
} else {await fs.writeFile(target,output);console.log('Built framework library: '+documents.length+' documents.');}
